<?php

require_once __DIR__ . '/auth.php';
require_once __DIR__ . '/../config.php';


/*
|--------------------------------------------------------------------------
| ONLY ALLOW POST
|--------------------------------------------------------------------------
*/

if ($_SERVER['REQUEST_METHOD'] !== 'POST')
{

    header('Location: phd.php');

    exit;

}


$id =
    $_POST['id'] ?? '';


/*
|--------------------------------------------------------------------------
| VALIDATE ID
|--------------------------------------------------------------------------
*/

if (
    $id === '' ||
    !ctype_digit((string)$id)
)
{

    header('Location: phd.php');

    exit;

}


$id =
    (int)$id;


/*
|--------------------------------------------------------------------------
| CHECK SCHOLAR EXISTS
|--------------------------------------------------------------------------
*/

$stmt = $pdo->prepare("
    SELECT id
    FROM phd_scholars
    WHERE id = ?
    LIMIT 1
");


$stmt->execute([
    $id
]);


if (!$stmt->fetch())
{

    header('Location: phd.php');

    exit;

}


/*
|--------------------------------------------------------------------------
| DELETE
|--------------------------------------------------------------------------
*/

try
{

    $stmt =
        $pdo->prepare("
            DELETE FROM phd_scholars
            WHERE id = ?
        ");


    $stmt->execute([
        $id
    ]);


    /*
    |--------------------------------------------------------------------------
    | REDIRECT
    |--------------------------------------------------------------------------
    */

    header(
        'Location: phd.php?success=deleted'
    );

    exit;

}
catch (PDOException $e)
{

    /*
    |--------------------------------------------------------------------------
    | DELETE FAILED
    |--------------------------------------------------------------------------
    */

    header(
        'Location: phd.php?success=delete_error'
    );

    exit;

}